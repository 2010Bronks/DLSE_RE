namespace GameUI
{
	bool bLogPageOpen = false;

	bool IsPageOpened(EGuiPages page);
	bool OpenPage(EGuiPages page);
	bool ClosePage(EGuiPages page);
}

static void __fastcall GameUI::OpenPageFunc(EGuiPages pageId)
{
	if (!pfnOpenPageFunc)
		return;

	pfnOpenPageFunc(pageId);

	int iPageId = static_cast<int>(pageId);
	bool isPageOpened = IsPageOpened(pageId);

	CHookChainArgs_OnGuiPageChange args{};
	args.emplace_back(iPageId);
	args.emplace_back(isPageOpened);
	CCallbackMgr::OnGuiPageChange().Run(args);

	if (bLogPageOpen)
	{
		LOG("[GUI_OpenPage] Page[{}]: \"{}\" | IsOpened[{}]", iPageId, GuiPageToStr(pageId), isPageOpened);
	}
}

bool GameUI::IsPageOpened(EGuiPages page)
{
	if (!s_pPageState)
		return false;

	return !s_pPageState[page];
}

bool GameUI::OpenPage(EGuiPages page)
{
	if (!pfnOpenPageFunc || !s_pPageState)
		return false;

	if (page == EGuiPages::eGP_Menu)
	{
		pfnOpenPageFunc(page);
		return true;
	}

	if (IsPageOpened(page))
		return true;
	else
		pfnOpenPageFunc(page);

	return true;
}

bool GameUI::ClosePage(EGuiPages page)
{
	if (!pfnOpenPageFunc || !s_pPageState)
		return false;

	if (page == EGuiPages::eGP_Menu)
	{
		pfnOpenPageFunc(page);
		return true;
	}

	if (!IsPageOpened(page))
		return true;
	else
		pfnOpenPageFunc(page);

	return true;
}

namespace GameUI
{
	GraphicResource* GetTexRes(EGuiTexs tex)
	{
		if (tex == EGuiTexs::eGE_Max)
			return nullptr;

		if (!s_pGuiTex_Res)
			return nullptr;

		return &s_pGuiTex_Res[tex];
	}

	const char* GuiTexToStr(EGuiTexs tex)
	{
		auto pRes = GetTexRes(tex);
		if (!pRes)
			return "<error>";

		if(!pRes->fname)
			return "<error>";

		return pRes->fname;
	}

	ProcessedFrame* GetTex(EGuiTexs tex)
	{
		if (tex == EGuiTexs::eGE_Max)
			return nullptr;

		if (!s_pGuiTex_Frames)
			return nullptr;

		if (!s_pGuiTex_Frames[tex])
			return nullptr;

		return s_pGuiTex_Frames[tex];
	}

	RawFrame8888* GetTexRaw(EGuiTexs tex)
	{
		if (tex == EGuiTexs::eGE_Max)
			return nullptr;

		if (!s_pGuiTex_Bmps)
			return nullptr;

		if (!s_pGuiTex_Bmps[tex])
			return nullptr;

		return s_pGuiTex_Bmps[tex];
	}
}

